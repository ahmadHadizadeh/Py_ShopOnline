PROVINCE_CHOICES = [("", "انتخاب استان")] + [
    (province, province) for province in PROVINCES_AND_CITIES.keys()
]


SELECT_TAILWIND_CLASS = (
    "w-full border border-gray-200 rounded-xl py-3.5 px-4 text-gray-800 "
    "focus:bg-white focus:border-indigo-500 focus:ring-4 focus:ring-indigo-500/10 outline-none transition-all "
    "bg-gray-50 appearance-none"  # appearance-none برای حذف ظاهر پیش‌فرض select
)

TAILWIND_INPUT_CLASS = (
    "w-full bg-gray-50 border border-gray-200 rounded-xl py-3.5 px-4 text-gray-800 "
    "focus:bg-white focus:border-indigo-500 focus:ring-4 focus:ring-indigo-500/10 outline-none transition-all"
)


class AddressForm(forms.ModelForm):
    province = forms.ChoiceField(
        choices=PROVINCE_CHOICES,
        label=_("استان"),
        widget=forms.Select(attrs={"class": f"{SELECT_TAILWIND_CLASS} select2-enable"}),
    )

    city = forms.ChoiceField(
        choices=[("", "ابتدا استان را انتخاب کنید")],
        label=_("شهر"),
        required=False,
        widget=forms.Select(
            attrs={
                "id": "id_city",
                "class": f"select2-enable {SELECT_TAILWIND_CLASS}",
                "disabled": "disabled",
            }
        ),
    )

    class Meta:
        model = Address
        fields = [
            "recipient_name",
            "phone_number",
            "postal_code",
            "province",
            "city",
            "address_line",
            "is_default",
        ]
        widgets = {
            "recipient_name": forms.TextInput(
                attrs={
                    "placeholder": _("مثلاً احمد هادی‌زاده"),
                    "class": TAILWIND_INPUT_CLASS,
                }
            ),
            "phone_number": forms.TextInput(
                attrs={
                    "placeholder": _("09xxxxxxxxx"),
                    "class": f"num-latin-input text-left dir-ltr font-sans {TAILWIND_INPUT_CLASS}",
                }
            ),
            "postal_code": forms.TextInput(
                attrs={
                    "placeholder": _("۱۰ رقم"),
                    "class": f"num-latin-input text-left dir-ltr font-sans {TAILWIND_INPUT_CLASS}",
                }
            ),
            "address_line": forms.Textarea(
                attrs={
                    "rows": 3,
                    "placeholder": _("آدرس دقیق پستی شامل نام کوچه، پلاک و واحد"),
                    "class": TAILWIND_INPUT_CLASS,
                }
            ),
        }

    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)

        province = None
        city_choices = [("", "ابتدا استان را انتخاب کنید")]

        if self.is_bound:
            province = self.data.get("province")
        elif self.instance and self.instance.pk:
            province = self.instance.province

        if province and province in PROVINCES_AND_CITIES:
            city_choices = [("", "انتخاب شهر")] + [
                (city, city) for city in PROVINCES_AND_CITIES[province]
            ]
            self.fields["city"].widget.attrs.pop("disabled", None)

        self.fields["city"].choices = city_choices

    def clean_phone_number(self):
        phone = self.cleaned_data.get("phone_number")
        if phone:
            phone = "".join(filter(str.isdigit, phone))
            if len(phone) not in (10, 11):
                raise forms.ValidationError(_("شماره تماس باید ۱۰ یا ۱۱ رقم باشد."))
        return phone

    def clean_postal_code(self):
        pc = self.cleaned_data.get("postal_code")
        if pc:
            pc = "".join(filter(str.isdigit, pc))
            if len(pc) != 10:
                raise forms.ValidationError(_("کد پستی باید دقیقاً ۱۰ رقم باشد."))
        return pc

    def clean(self):
        cleaned_data = super().clean()
        province = cleaned_data.get("province")
        city = cleaned_data.get("city")

        if province and province not in PROVINCES_AND_CITIES:
            raise forms.ValidationError(_("استان انتخاب شده معتبر نیست."))

        if province and not city:
            raise forms.ValidationError(
                _("لطفاً شهر مربوط به استان انتخاب شده را انتخاب کنید.")
            )

        if not province and city:
            raise forms.ValidationError(_("لطفاً ابتدا استان را انتخاب کنید."))

        if province and city:
            valid_cities = PROVINCES_AND_CITIES.get(province, [])
            if city not in valid_cities:
                raise forms.ValidationError(
                    _("شهر انتخاب شده برای این استان معتبر نیست.")
                )

        return cleaned_data
